"""
quantile_normalizer.py

Frozen empirical quantile mapping for deployment.

The calibration mapping must first be generated by
calibrate_sensors.py.

Mapping:

    sensor value
         |
         v
    sensor percentile
         |
         v
    training/API value at same percentile
         |
         v
    aligned value
"""


import json
from pathlib import Path

import numpy as np


class FixedQuantileMapper:
    """
    Apply a pre-computed sensor -> training-domain
    quantile mapping.

    IMPORTANT:
        This class does NOT learn during prediction.

        The mapping is generated offline using the
        calibration period and then frozen.
    """

    def __init__(
        self,
        percentiles,
        sensor_values,
        training_values
    ):

        self.percentiles = np.asarray(
            percentiles,
            dtype=float
        )

        self.sensor_values = np.asarray(
            sensor_values,
            dtype=float
        )

        self.training_values = np.asarray(
            training_values,
            dtype=float
        )

        self._validate()

    def _validate(self):

        if not (
            len(self.percentiles)
            == len(self.sensor_values)
            == len(self.training_values)
        ):
            raise ValueError(
                "Percentiles, sensor_values and "
                "training_values must have the same length."
            )

        if len(self.percentiles) < 2:
            raise ValueError(
                "At least two quantile points are required."
            )

        if not np.all(
            np.diff(self.percentiles) >= 0
        ):
            raise ValueError(
                "Percentiles must be ascending."
            )

        if not np.all(
            np.isfinite(self.sensor_values)
        ):
            raise ValueError(
                "sensor_values contains invalid values."
            )

        if not np.all(
            np.isfinite(self.training_values)
        ):
            raise ValueError(
                "training_values contains invalid values."
            )

        # np.interp requires ascending x values.
        if not np.all(
            np.diff(self.sensor_values) >= 0
        ):
            raise ValueError(
                "sensor_values must be ascending."
            )

    def transform(
        self,
        value: float
    ) -> float:
        """
        Transform one sensor value into the
        training-domain scale.
        """

        value = float(value)

        if not np.isfinite(value):
            raise ValueError(
                f"Invalid sensor value: {value}"
            )
        # Step 1:
        # Find percentile of the sensor value
        percentile = np.interp(
            value,
            self.sensor_values,
            self.percentiles
        )
        # Step 2:
        # Map same percentile onto training distribution
        aligned_value = np.interp(
            percentile,
            self.percentiles,
            self.training_values
        )

        return float(aligned_value)

    def transform_array(
        self,
        values
    ):
        """
        Transform an array/list of sensor values.
        """

        values = np.asarray(
            values,
            dtype=float
        )

        percentiles = np.interp(
            values,
            self.sensor_values,
            self.percentiles
        )

        return np.interp(
            percentiles,
            self.percentiles,
            self.training_values
        )


class SensorQuantileCalibrator:
    """
    Loads the frozen quantile mappings for one station.

    Example:

        calibrator = SensorQuantileCalibrator(
            "calibration/ST01_quantile_mapping.json"
        )

        aligned = calibrator.transform({
            "pm2_5_ugm3": 31.2,
            "co_ugm3": 1800,
            "no2_ugm3": 80,
            "temperature_c": 30.2,
            "humidity_pct": 74
        })
    """

    def __init__(
        self,
        calibration_path
    ):

        calibration_path = Path(
            calibration_path
        )

        if not calibration_path.exists():
            raise FileNotFoundError(
                f"Calibration file not found: "
                f"{calibration_path}"
            )

        with open(
            calibration_path,
            "r",
            encoding="utf-8"
        ) as f:

            config = json.load(f)

        self.metadata = config.get(
            "_metadata",
            {}
        )

        self.mappers = {}

        for feature, spec in config.items():

            # Metadata is not a feature
            if feature.startswith("_"):
                continue

            if not isinstance(spec, dict):
                continue

            self.mappers[feature] = (
                FixedQuantileMapper(
                    percentiles=spec["percentiles"],
                    sensor_values=spec["sensor_values"],
                    training_values=spec["training_values"]
                )
            )

    def transform(
        self,
        readings: dict
    ) -> dict:
        """
        Transform a dictionary of sensor readings.

        Unknown fields pass through unchanged.
        """

        result = {}

        for feature, value in readings.items():

            mapper = self.mappers.get(
                feature
            )

            if mapper is None:
                result[feature] = value
            else:
                result[feature] = (
                    mapper.transform(value)
                )

        return result

    def transform_feature(
        self,
        feature: str,
        value: float
    ) -> float:

        if feature not in self.mappers:
            return float(value)

        return self.mappers[
            feature
        ].transform(value)

    def get_metadata(self):
        return self.metadata